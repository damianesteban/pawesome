-- Enable UUID extension if not already enabled
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";


-- Custom types

create type public.animal_status as enum ('Available', 'Adopted', 'In Treatment', 'In Foster', 'Pending');
create type public.adoption_request_status as enum ('Pending', 'Approved', 'Rejected');

-- ADOPTERS
create table public.adopters (
  id          bigint generated by default as identity primary key,
  first_name  text not null,
  last_name   text not null,
  email       text not null
);

-- ANIMALS
create table public.animals (
    id  bigint generated by default as identity primary key,
    name VARCHAR(100) NOT NULL,
    breed VARCHAR(100),
    age INTEGER CHECK (age >= 0),
    status animal_status default 'Available'::public.animal_status,
    created_at   timestamp with time zone default timezone('utc'::text, now()) not null
);

comment on table public.animals is 'Data for each animal.';

-- ADOPTION REQUESTS
create table public.adoption_requests (
    id bigint generated by default as identity primary key,
    user_id bigint references public.adopters(id) not null,
    animal_id bigint references public.animals(id) not null,
    status adoption_request_status default 'Pending'::public.adoption_request_status,
    request_date timestamp with time zone default timezone('utc'::text, now()) not null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

comment on table public.adoption_requests is 'Data for each adoption request.';